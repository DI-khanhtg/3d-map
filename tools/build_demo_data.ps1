# build_demo_data.ps1
# ---------------------------------------------------------------------------
# Builds the demo data for the 3D viewer, for every line in data/demo_scenario.json:
#   1. Stitches the OSM route relation into one centreline (loop or point-to-point)
#   2. Cuts it into fixed-length sections (kilometre posts / kiro-tei)
#   3. Generates MOCK inspection results (3 campaigns): structure + track defects
#
# Output (consumed by viewer/index.html):
#   viewer/data/lines.js              window.RAIL_LINES = [ {id, name, city, ...}, ... ]
#   viewer/data/<id>/rail_line.js     window.RAIL_LINE  = {...}
#   viewer/data/<id>/inspection.js    window.INSPECTION = {...}
#   data/assets_register/<id>.sample.json   structure ledger extract for the pipeline
#
# When real drone data exists, pipeline/run.py produces inspection.js with the
# same schema and this script is only needed for the rail centreline.
#
# Usage:  powershell -ExecutionPolicy Bypass -File tools\build_demo_data.ps1
# (ASCII only on purpose: Windows PowerShell 5.1 reads BOM-less files as ANSI.)
# ---------------------------------------------------------------------------
param([string]$Root = (Split-Path -Parent $PSScriptRoot))
$ErrorActionPreference = 'Stop'
[System.Threading.Thread]::CurrentThread.CurrentCulture = [System.Globalization.CultureInfo]::InvariantCulture

function Read-JsonFile([string]$path) {
    return (Get-Content -Raw -Encoding UTF8 $path | ConvertFrom-Json)
}
function Write-Utf8([string]$path, [string]$text) {
    $dir = Split-Path -Parent $path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
    [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding($false)))
}
function Write-JsFile([string]$path, [string]$varName, $obj) {
    $json = ConvertTo-Json -InputObject $obj -Depth 12 -Compress
    $text = "// AUTO-GENERATED by tools/build_demo_data.ps1 - do not edit by hand`n" +
            "window.$varName = $json;`n"
    Write-Utf8 $path $text
    Write-Host ("  wrote {0} ({1:N0} bytes)" -f $path.Substring($Root.Length + 1), $text.Length)
}

# ---------- geometry helpers (lon/lat in degrees, distances in metres) ----------
$R_EARTH = 6371008.8
$DEG = [math]::PI / 180.0
function Get-Dist($a, $b) {
    $dLat = ($b[1] - $a[1]) * $DEG
    $dLon = ($b[0] - $a[0]) * $DEG
    $s1 = [math]::Sin($dLat / 2); $s2 = [math]::Sin($dLon / 2)
    $h = $s1 * $s1 + [math]::Cos($a[1] * $DEG) * [math]::Cos($b[1] * $DEG) * $s2 * $s2
    return 2 * $R_EARTH * [math]::Asin([math]::Min(1.0, [math]::Sqrt($h)))
}
function Get-Mod([double]$x, [double]$m) { return (($x % $m) + $m) % $m }
function Round6($v) { return [math]::Round([double]$v, 6) }

# ---------- deterministic RNG (so the demo is reproducible) ----------
$script:rng = [long]0
function Set-Seed([long]$s) { $script:rng = $s % 2147483648 }
function Get-Rand {
    $script:rng = ([long]$script:rng * 1103515245 + 12345) % 2147483648
    return [double]$script:rng / 2147483648.0
}
function Get-RandRange([double]$lo, [double]$hi) { return $lo + (Get-Rand) * ($hi - $lo) }
function Get-Pick($arr) { return $arr[[int][math]::Floor((Get-Rand) * $arr.Count)] }

# ---------- chainage helpers (use the current line: $chain, $cum, $TOTAL, $LOOP) ----------
function Norm-S([double]$s) {
    if ($LOOP) { return (Get-Mod $s $TOTAL) }
    return [math]::Max(0.0, [math]::Min($TOTAL, $s))
}
function Get-PointAt([double]$s) {
    # returns @(lon, lat, bearingRad, vertexIndex) at distance s along the chain
    $s = Norm-S $s
    $lo = 0; $hi = $cum.Count - 1
    while ($hi - $lo -gt 1) { $mid = [int](($lo + $hi) / 2); if ($cum[$mid] -le $s) { $lo = $mid } else { $hi = $mid } }
    $a = $chain[$lo]; $b = $chain[$hi]
    $seg = $cum[$hi] - $cum[$lo]; $t = 0.0; if ($seg -gt 0) { $t = ($s - $cum[$lo]) / $seg }
    $lon = $a[0] + ($b[0] - $a[0]) * $t
    $lat = $a[1] + ($b[1] - $a[1]) * $t
    $dx = ($b[0] - $a[0]) * [math]::Cos($lat * $DEG); $dy = ($b[1] - $a[1])
    return @($lon, $lat, [math]::Atan2($dx, $dy), $lo)
}
function Get-Offset($p, [double]$lateral) {
    # shift point p perpendicular (to the right of travel direction) by $lateral metres
    $brg = $p[2] + [math]::PI / 2
    $dN = [math]::Cos($brg) * $lateral; $dE = [math]::Sin($brg) * $lateral
    return @(($p[0] + ($dE / ($R_EARTH * [math]::Cos($p[1] * $DEG))) / $DEG), ($p[1] + ($dN / $R_EARTH) / $DEG))
}
function Get-SDist([double]$a, [double]$b) {
    # unsigned distance between two chainages (loop aware)
    if ($LOOP) { return [math]::Abs((Get-Mod ($a - $b + $TOTAL / 2) $TOTAL) - $TOTAL / 2) }
    return [math]::Abs($a - $b)
}
function Get-Arc([string]$from, [string]$to, [string]$via) {
    # arc between two stations: @(startChainage, direction(+1/-1), length)
    $sA = $stKm[$from]; $sB = $stKm[$to]
    if ($null -eq $sA -or $null -eq $sB) { throw "unknown station in zone/hotspot: $from / $to" }
    if (-not $LOOP) { $d = $sB - $sA; if ($d -ge 0) { return @($sA, 1, $d) } else { return @($sA, -1, -$d) } }
    $fwd = Get-Mod ($sB - $sA) $TOTAL
    if ($via) { $useFwd = ((Get-Mod ($stKm[$via] - $sA) $TOTAL) -le $fwd) } else { $useFwd = ($fwd -le $TOTAL / 2) }
    if ($useFwd) { return @($sA, 1, $fwd) }
    return @($sA, -1, ($TOTAL - $fwd))
}
function Test-InArc([double]$s, $arc) {
    if ($LOOP) { $u = Get-Mod (($s - $arc[0]) * $arc[1]) $TOTAL } else { $u = ($s - $arc[0]) * $arc[1] }
    return ($u -ge 0 -and $u -le $arc[2])
}
function Get-SpecPos($spec) {
    # chainage of a zone / hotspot: near + offset_m, or between [A, B] + t
    if ($spec.near) { return (Norm-S ($stKm[$spec.near] + $spec.offset_m)) }
    $arc = Get-Arc $spec.between[0] $spec.between[1] $null
    return (Norm-S ($arc[0] + $arc[1] * [double]$spec.t * $arc[2]))
}
function Get-StationPair([double]$s) {
    # stations before / after chainage s
    $n = $stations.Count
    if ($LOOP) {
        $prev = $stations[-1]; $next = $stations[0]
        foreach ($st in $stations) { if ($st.km * 1000 -le $s) { $prev = $st } }
        foreach ($st in $stations) { if ($st.km * 1000 -gt $s) { $next = $st; break } }
        return @($prev.name, $next.name)
    }
    $i = 0
    for ($k = 0; $k -lt $n; $k++) { if ($stations[$k].km * 1000 -le $s) { $i = $k } }
    $i = [math]::Min($i, $n - 2)
    return @($stations[$i].name, $stations[$i + 1].name)
}
function Get-AssetAt([double]$s) {
    # point structures (bridges) first, then station-to-station zones, then the default
    foreach ($z in $zones) {
        if ($null -ne $z.center) {
            # tolerance >= half a section so short structures still claim the section they sit in
            $tol = [math]::Max($z.length_m / 2, $L / 2)
            if ((Get-SDist $s $z.center) -le $tol) { return @($z.asset, $z.label, $z.label_en) }
        }
    }
    foreach ($z in $zones) { if ($null -ne $z.arc -and (Test-InArc $s $z.arc)) { return @($z.asset, $null, $null) } }
    return @($defaultAsset, $null, $null)
}

# ---------- assessment helpers ----------
$scn = Read-JsonFile "$Root/data/demo_scenario.json"
$L = [double]$scn.section_length_m
$NC = $scn.campaigns.Count
$grades = @($scn.grades)
function Get-Grade([double]$r) { foreach ($g in $grades) { if ($r -ge $g.min) { return $g.id } }; return 'S' }
function Get-Crit($assetKey, $compName) {
    foreach ($c in $scn.asset_types.$assetKey.components) { if ($c[0] -eq $compName) { return [double]$c[1] } }
    return 0.7
}
# risk = 0.8 * severity * (0.6 + 0.4 * criticality) + 0.2 * growth   (same formula as pipeline/stages/s6_assess.py)
function Get-Risk($sev, $prevSev, [double]$crit) {
    if ($null -eq $sev) { return $null }
    if ($null -eq $prevSev) { $g = 0.3 } else { $g = [math]::Max(0.0, [math]::Min(1.0, ($sev - $prevSev) / 0.3)) }
    return [math]::Round([math]::Min(1.0, 0.8 * $sev * (0.6 + 0.4 * $crit) + 0.2 * $g), 3)
}
function Add-Defect([double]$s, [string]$type, [string]$comp, $sevArr, $valArr, $widthArr, $confArr, [string]$note, [string]$noteEn, [bool]$story) {
    $s = Norm-S $s
    $k = [int][math]::Floor($s / $L); if ($k -ge $nSec) { $k = $nSec - 1 }
    $sec = $sections[$k]
    $p = Get-PointAt $s
    $side = 1; if ((Get-Rand) -lt 0.5) { $side = -1 }
    # category: track if the component is part of the track, else the defect type's default
    $isTrack = (@($scn.track_components) -contains $comp) -or ($scn.defect_types.$type.cat -eq 'track')
    $cat = 'structure'; if ($isTrack) { $cat = 'track' }
    # structure defects sit on the structure face; track defects on the rails
    if ($isTrack) { $lat = Get-RandRange 0.4 2.2 } else { $lat = Get-RandRange 2.5 6.0 }
    $q = Get-Offset $p ($side * $lat)
    if ($isTrack) { $z = [math]::Round($sec.height_m + 0.2, 1) } else { $z = [math]::Round($sec.height_m * (Get-RandRange 0.3 1.0), 1) }
    $crit = Get-Crit $sec.asset $comp
    if ($story -and -not (@($scn.asset_types.($sec.asset).components | ForEach-Object { $_[0] }) -contains $comp)) {
        Write-Warning ("hotspot {0} at {1:N0} m: component not found on asset '{2}'" -f $type, $s, $sec.asset)
    }
    $obs = @(); $risk = @(); $grade = @()
    for ($c = 0; $c -lt $NC; $c++) {
        $sev = $sevArr[$c]
        if ($null -eq $sev) { $obs += , $null; $risk += , $null; $grade += , $null; continue }
        $prev = $null; if ($c -gt 0) { $prev = $sevArr[$c - 1] }
        $r = Get-Risk $sev $prev $crit
        $o = [ordered]@{
            sev = [math]::Round($sev, 3); conf = [math]::Round($confArr[$c], 2)
            value = $valArr[$c]
            frame = [ordered]@{ flight = ('F-{0}-{1:D2}' -f $scn.campaigns[$c].id, ([int][math]::Floor($s / 2000) + 1)); t = [math]::Round((Get-Mod $s 2000) / 6.5 + (Get-RandRange 0 4), 1) }
        }
        if ($null -ne $widthArr) { $o.width_mm = $widthArr[$c] }
        $obs += , $o; $risk += , $r; $grade += , (Get-Grade $r)
    }
    $id = 'D-{0:D4}' -f ($defects.Count + 1)
    $defects.Add([ordered]@{
        id = $id; section = $sec.id; km = [math]::Round($s / 1000, 3)
        lon = (Round6 $q[0]); lat = (Round6 $q[1]); z = $z
        bearing = [math]::Round($p[2] / $DEG, 1)
        type = $type; component = $comp; cat = $cat; asset = $sec.asset
        crit = $crit; story = $story; note = $note; note_en = $noteEn
        obs = $obs; risk = $risk; grade = $grade
    })
}

$index = New-Object System.Collections.Generic.List[object]

foreach ($ln in $scn.lines) {
    Write-Host ""
    Write-Host ("=== {0} ({1}) ===" -f $ln.id, $ln.name_en)
    $LOOP = [bool]$ln.loop
    $defaultAsset = $scn.default_asset; if ($ln.default_asset) { $defaultAsset = $ln.default_asset }

    # =====================================================================
    # 1. Stitch OSM route relation into one ordered centreline
    # =====================================================================
    Write-Host "[1/3] Stitching OSM relation..."
    $rel   = (Read-JsonFile "$Root/$($ln.relation_file)").elements[0]
    $stops = (Read-JsonFile "$Root/$($ln.stops_file)").elements

    $ways = @($rel.members | Where-Object { $_.type -eq 'way' -and $_.role -eq '' })
    $chain = New-Object System.Collections.Generic.List[object]
    foreach ($g in $ways[0].geometry) { $chain.Add(@([double]$g.lon, [double]$g.lat)) }
    $maxGap = 0.0
    for ($i = 1; $i -lt $ways.Count; $i++) {
        $pts = @($ways[$i].geometry | ForEach-Object { , @([double]$_.lon, [double]$_.lat) })
        if ($i -eq 1) {
            # orient the first way so that it connects to the second one
            $dHead = [math]::Min((Get-Dist $chain[0] $pts[0]), (Get-Dist $chain[0] $pts[-1]))
            $dTail = [math]::Min((Get-Dist $chain[$chain.Count - 1] $pts[0]), (Get-Dist $chain[$chain.Count - 1] $pts[-1]))
            if ($dHead -lt $dTail) { $chain.Reverse() }
        }
        $last = $chain[$chain.Count - 1]
        $dF = Get-Dist $last $pts[0]
        $dL = Get-Dist $last $pts[-1]
        if ($dL -lt $dF) { [array]::Reverse($pts); $dF = $dL }
        if ($dF -gt $maxGap) { $maxGap = $dF }
        $start = 0; if ($dF -lt 1.0) { $start = 1 }
        for ($k = $start; $k -lt $pts.Count; $k++) { $chain.Add($pts[$k]) }
    }
    $cum = New-Object System.Collections.Generic.List[double]
    $cum.Add(0.0)
    for ($i = 1; $i -lt $chain.Count; $i++) { $cum.Add($cum[$i - 1] + (Get-Dist $chain[$i - 1] $chain[$i])) }
    $TOTAL = $cum[$cum.Count - 1]
    Write-Host ("  ways={0} vertices={1} length={2:N0} m  max-gap={3:N1} m  end-to-end={4:N1} m" -f `
        $ways.Count, $chain.Count, $TOTAL, $maxGap, (Get-Dist $chain[0] $chain[$chain.Count - 1]))

    # ---------- stations: snap to chain -> chainage ----------
    $names = @{}
    foreach ($e in $stops) { $names[[string]$e.id] = $e.tags }
    $stationList = New-Object System.Collections.Generic.List[object]
    foreach ($m in @($rel.members | Where-Object { $_.type -eq 'node' -and $_.role -eq 'stop' })) {
        $p = @([double]$m.lon, [double]$m.lat)
        $best = 0; $bd = 1e18
        for ($i = 0; $i -lt $chain.Count; $i++) { $d = Get-Dist $p $chain[$i]; if ($d -lt $bd) { $bd = $d; $best = $i } }
        $t = $names[[string]$m.ref]
        if ($null -eq $t) { continue }
        $nm = [string]$t.name
        if (@($stationList | Where-Object { $_.name -eq $nm }).Count -gt 0) { continue }
        $en = [string]$t.'name:en'
        if ($ln.name_en_override -and $ln.name_en_override.$nm) { $en = [string]$ln.name_en_override.$nm }
        $stationList.Add([ordered]@{ name = $nm; name_en = $en; km = [math]::Round($cum[$best] / 1000, 3); lon = (Round6 $chain[$best][0]); lat = (Round6 $chain[$best][1]) })
    }
    $stations = @($stationList | Sort-Object { $_.km })
    $stKm = @{}; foreach ($s in $stations) { $stKm[$s.name] = $s.km * 1000 }
    Write-Host ("  stations={0}: {1}" -f $stations.Count, (($stations | ForEach-Object { $_.name_en }) -join ', '))

    # ---------- structure zones -> chainage ----------
    $zones = @()
    foreach ($z in $ln.asset_zones) {
        if ($z.near -or $z.between) { $zones += , @{ asset = $z.asset; label = $z.label; label_en = $z.label_en; length_m = [double]$z.length_m; center = (Get-SpecPos $z); arc = $null } }
        else { $zones += , @{ asset = $z.asset; label = $null; label_en = $null; center = $null; arc = (Get-Arc $z.from $z.to $z.via) } }
    }

    # write rail line (decimated a bit: drop vertices closer than 4 m)
    $lineCoords = New-Object System.Collections.Generic.List[object]
    $lineCoords.Add(@((Round6 $chain[0][0]), (Round6 $chain[0][1])))
    $lastKept = $chain[0]
    for ($i = 1; $i -lt $chain.Count; $i++) {
        if ((Get-Dist $lastKept $chain[$i]) -ge 4.0 -or $i -eq $chain.Count - 1) { $lineCoords.Add(@((Round6 $chain[$i][0]), (Round6 $chain[$i][1]))); $lastKept = $chain[$i] }
    }
    $lineInfo = [ordered]@{ id = $ln.id; name = $ln.name; name_en = $ln.name_en; city = $ln.city; city_en = $ln.city_en; loop = $LOOP }
    Write-JsFile "$Root/viewer/data/$($ln.id)/rail_line.js" 'RAIL_LINE' ([ordered]@{
        id = $ln.id; name = $ln.name; name_en = $ln.name_en; city = $ln.city; city_en = $ln.city_en; loop = $LOOP
        length_m = [math]::Round($TOTAL, 1)
        source = "OpenStreetMap contributors (ODbL), relation $($ln.osm_relation)"
        major = @($ln.major)
        coordinates = $lineCoords.ToArray()
        stations = $stations
    })

    # =====================================================================
    # 2. Sections (fixed length, with chainage)
    # =====================================================================
    Write-Host "[2/3] Building sections..."
    $nSec = [int][math]::Ceiling($TOTAL / $L)
    $sections = New-Object System.Collections.Generic.List[object]
    for ($k = 0; $k -lt $nSec; $k++) {
        $s0 = $k * $L; $s1 = [math]::Min($TOTAL, ($k + 1) * $L)
        $mid = ($s0 + $s1) / 2
        $asset = Get-AssetAt $mid
        $h = [double]$scn.asset_types.($asset[0]).height_m
        $path = New-Object System.Collections.Generic.List[object]
        $p0 = Get-PointAt $s0; $path.Add(@((Round6 $p0[0]), (Round6 $p0[1]), $h))
        for ($i = 0; $i -lt $cum.Count; $i++) { if ($cum[$i] -gt $s0 -and $cum[$i] -lt $s1) { $path.Add(@((Round6 $chain[$i][0]), (Round6 $chain[$i][1]), $h)) } }
        $p1 = Get-PointAt ($s1 - 0.01); $path.Add(@((Round6 $p1[0]), (Round6 $p1[1]), $h))
        $sections.Add([ordered]@{
            id = ('{0}-S{1:D3}' -f $ln.id, $k)
            idx = $k
            from_km = [math]::Round($s0 / 1000, 3); to_km = [math]::Round($s1 / 1000, 3)
            between = (Get-StationPair $mid)
            asset = $asset[0]; asset_label = $asset[1]; asset_label_en = $asset[2]; height_m = $h
            path = $path.ToArray()
            risk = $null; grade = $null; defects = @()
        })
    }
    Write-Host ("  sections={0} x {1} m" -f $nSec, $L)

    # =====================================================================
    # 3. Mock inspection results
    # =====================================================================
    Write-Host "[3/3] Generating mock inspection results..."
    Set-Seed ([long]$ln.seed)
    $defects = New-Object System.Collections.Generic.List[object]

    # 3a. scripted hotspots (the "story" of the demo)
    foreach ($h in $ln.hotspots) {
        $width = $null; if ($h.width_mm) { $width = @($h.width_mm) }
        Add-Defect (Get-SpecPos $h) $h.type $h.component @($h.sev) @($h.value) $width @($h.conf) $h.note $h.note_en $true
    }
    # 3b. random background defects (mostly minor)
    for ($n = 0; $n -lt [int]$ln.random_defects; $n++) {
        $s = Get-RandRange 0 $TOTAL
        $k = [int][math]::Floor($s / $L); if ($k -ge $nSec) { $k = $nSec - 1 }
        $comp = Get-Pick @($scn.asset_types.($sections[$k].asset).components)
        $type = Get-Pick @($comp[2])
        $ti = $scn.defect_types.$type
        $scale = [double]$ti.scale
        $first = Get-Pick @(0, 0, 0, 1, 1, 2)
        $base = Get-RandRange 0.08 0.40
        $gr = Get-RandRange 0.0 0.06
        $sevA = @(); $valA = @(); $confA = @(); $widA = @()
        for ($c = 0; $c -lt $NC; $c++) {
            if ($c -lt $first) { $sevA += , $null; $valA += , $null; $confA += , $null; $widA += , $null; continue }
            $sv = [math]::Min(0.95, $base + $gr * ($c - $first))
            $sevA += , $sv
            $v = $scale * $sv * (Get-RandRange 0.8 1.1)
            if ($ti.int) { $v = [math]::Max(1, [math]::Round($v)) } else { $v = [math]::Round($v, 1) }
            $valA += , $v
            $confA += , (Get-RandRange 0.62 0.95)
            $widA += , ([math]::Round(0.1 + $sv * 0.6, 2))
        }
        if ($type -ne 'crack') { $widA = $null }
        Add-Defect $s $type $comp[0] $sevA $valA $widA $confA '' '' $false
    }

    # 3c. roll defects up into sections (section risk = max defect risk, else a small baseline)
    foreach ($sec in $sections) {
        $mine = @($defects | Where-Object { $_.section -eq $sec.id })
        $sec.defects = @($mine | ForEach-Object { $_.id })
        $rArr = @(); $gArr = @()
        for ($c = 0; $c -lt $NC; $c++) {
            $mx = 0.02 + 0.06 * (Get-Rand)
            foreach ($d in $mine) { if ($null -ne $d.risk[$c] -and $d.risk[$c] -gt $mx) { $mx = $d.risk[$c] } }
            $rArr += , ([math]::Round($mx, 3)); $gArr += , (Get-Grade $mx)
        }
        $sec.risk = $rArr; $sec.grade = $gArr
    }

    $lastC = $NC - 1
    $cnt = @{}; foreach ($g in $grades) { $cnt[$g.id] = 0 }
    $nTrack = 0
    foreach ($d in $defects) {
        if ($null -ne $d.grade[$lastC]) { $cnt[$d.grade[$lastC]]++ }
        if ($d.cat -eq 'track') { $nTrack++ }
    }
    Write-Host ("  defects={0} (track {1})  latest grades: AA={2} A1={3} A2={4} B={5} C={6} S={7}" -f $defects.Count, $nTrack, $cnt.AA, $cnt.A1, $cnt.A2, $cnt.B, $cnt.C, $cnt.S)

    # campaign statistics scale with the line length (one flight ~ 2 km)
    $flightsN = [int][math]::Ceiling($TOTAL / 2000)
    $camps = @()
    foreach ($cp in $scn.campaigns) {
        $camps += , [ordered]@{
            id = $cp.id; date = $cp.date; label = $cp.label
            videos = $flightsN; flights = $flightsN
            images = [int][math]::Round($TOTAL / 1000 * $cp.images_per_km)
            frames = [int][math]::Round($TOTAL / 1000 * $cp.frames_per_km)
            gsd_mm = $cp.gsd_mm
        }
    }

    Write-JsFile "$Root/viewer/data/$($ln.id)/inspection.js" 'INSPECTION' ([ordered]@{
        schema = 'rail-inspection/0.2'
        generated_by = 'tools/build_demo_data.ps1 (MOCK)'
        mock = $true
        line = $lineInfo
        section_length_m = $L
        campaigns = $camps
        defect_types = $scn.defect_types
        asset_types = $scn.asset_types
        grades = $scn.grades
        risk_formula = 'risk = 0.8*severity*(0.6+0.4*criticality) + 0.2*growth'
        sections = $sections.ToArray()
        defects = $defects.ToArray()
    })

    # sample asset register (structure ledger extract) for pipeline/config.example.yaml
    $reg = New-Object System.Collections.Generic.List[object]
    foreach ($sec in $sections) {
        $lastReg = $null; if ($reg.Count -gt 0) { $lastReg = $reg[$reg.Count - 1] }
        if ($null -ne $lastReg -and $lastReg.asset -eq $sec.asset -and $lastReg.label -eq $sec.asset_label) { $lastReg.to_km = $sec.to_km }
        else { $reg.Add([ordered]@{ from_km = $sec.from_km; to_km = $sec.to_km; asset = $sec.asset; label = $sec.asset_label; label_en = $sec.asset_label_en }) }
    }
    Write-Utf8 "$Root/data/assets_register/$($ln.id).sample.json" (ConvertTo-Json -InputObject $reg.ToArray() -Depth 4)
    Write-Host ("  wrote data/assets_register/{0}.sample.json ({1} entries)" -f $ln.id, $reg.Count)

    $index.Add([ordered]@{
        id = $ln.id; name = $ln.name; name_en = $ln.name_en; city = $ln.city; city_en = $ln.city_en
        length_m = [math]::Round($TOTAL, 1); stations = $stations.Count; defects = $defects.Count
    })
}

Write-Host ""
Write-JsFile "$Root/viewer/data/lines.js" 'RAIL_LINES' $index.ToArray()
Write-Host "Done."
